print(">>> Estimando sistema...")
codes = gdf["code"].tolist()
panel_s = (panel.set_index(["year", "code"])
           .reindex(pd.MultiIndex.from_product([years, codes], names=["year", "code"]))
           .reset_index())

coef_rows = []
Phi = np.zeros((3, 3))
Rho = np.zeros((3, 3))
Theta = np.zeros((3, 3))

for i, dep in enumerate(VARIABLES):
    yv = panel_s[dep].values.astype(float)
    y_lag = panel_s.groupby("code")[dep].shift(1).values
    Wy = np.zeros(len(yv))
    Wy_lag = np.zeros(len(yv))
    for t_idx, yr in enumerate(years):
        mask = panel_s["year"] == yr
        yt = panel_s.loc[mask, dep].values
        Wy[mask] = w.sparse @ yt
        if t_idx > 0:
            prev = years[t_idx - 1]
            yprev = panel_s.loc[panel_s["year"] == prev, dep].values
            Wy_lag[mask] = w.sparse @ yprev

    X_list = [y_lag, Wy_lag]
    names = [f"{dep}_L1", f"W_{dep}_L1"]
    for ov in VARIABLES:
        if ov == dep:
            continue
        ov_lag = panel_s.groupby("code")[ov].shift(1).values
        X_list.append(ov_lag)
        names.append(f"{ov}_L1")
        Wov = np.zeros(len(yv))
        for t_idx, yr in enumerate(years):
            if t_idx == 0:
                continue
            prev = years[t_idx - 1]
            ovp = panel_s.loc[panel_s["year"] == prev, ov].values
            Wov[panel_s["year"] == yr] = w.sparse @ ovp
        X_list.append(Wov)
        names.append(f"W_{ov}_L1")

    X = np.column_stack(X_list)
    valid = ~np.isnan(y_lag)
    y_ok, X_ok, Wy_ok = yv[valid], X[valid], Wy[valid]

    try:
        gamma = np.linalg.lstsq(X_ok, Wy_ok, rcond=None)[0]
        Wy_hat = X_ok @ gamma
        X2 = np.column_stack([X_ok, Wy_hat])
        nms = names + [f"W_{dep}"]
        beta = np.linalg.lstsq(X2, y_ok, rcond=None)[0]
    except Exception:
        X2 = np.column_stack([X_ok, Wy_ok])
        nms = names + [f"W_{dep}"]
        beta = np.linalg.lstsq(X2, y_ok, rcond=None)[0]

    for nm, b in zip(nms, beta):
        coef_rows.append({"equation": dep, "variable": nm, "coef": round(float(b), 4)})

    Phi[i, i] = next((b for nm, b in zip(nms, beta) if nm == f"{dep}_L1"), 0.0)
    Rho[i, i] = next((b for nm, b in zip(nms, beta) if nm == f"W_{dep}"), 0.0)
    Theta[i, i] = next((b for nm, b in zip(nms, beta) if nm == f"W_{dep}_L1"), 0.0)

coef_df = pd.DataFrame(coef_rows)
rho_bar = float(np.clip(np.mean(np.diag(Rho)), -0.85, 0.85))

try:
    max_mod = float(np.max(np.abs(eigvals(Phi + 0.5 * Theta))))
    stable = max_mod < 1.0
except Exception:
    max_mod, stable = np.nan, False

try:
    S = inv(np.eye(w.n) - rho_bar * w.full()[0])
    direct = float(np.mean(np.diag(S)))
    total = float(np.mean(S.sum(1)))
    indirect = total - direct
except Exception:
    direct = indirect = total = np.nan

