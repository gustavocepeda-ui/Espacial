def make_map(year: int, variable: str) -> str:
    """Mapa coroplético robusto – corrige códigos y NaNs para educ/crime/lights."""
    try:
        year = int(year)
        variable = str(variable)

        # 1. Asegurar que ambos lados tengan el mismo tipo de código
        gdf_tmp = gdf.copy()
        gdf_tmp["code"] = gdf_tmp["code"].astype(str).str.zfill(2)

        panel_year = panel.loc[panel["year"] == year].copy()
        if panel_year.empty:
            return f"<p style='color:red;padding:20px;'>No hay datos para el año {year}</p>"

        panel_year["code"] = panel_year["code"].astype(str).str.zfill(2)

        # 2. Extraer solo la variable pedida (evita columnas duplicadas)
        data = (
            panel_year[["code", variable]]
            .drop_duplicates(subset=["code"])
            .set_index("code")
            .reindex(gdf_tmp["code"])
            .reset_index()
        )

        gdf_p = gdf_tmp.merge(data, on="code", how="left")

        # 3. Rellenar posibles NaNs residuales con la media del año (evita mapa completamente gris)
        if gdf_p[variable].isna().any():
            mean_val = float(panel_year[variable].mean())
            gdf_p[variable] = gdf_p[variable].fillna(mean_val)

        # 4. Crear mapa
        m = folium.Map(location=[4.5, -74.0], zoom_start=5, tiles="CartoDB positron")

        vals = gdf_p[variable].astype(float)
        vmin, vmax = float(vals.min()), float(vals.max())
        if vmin == vmax:          # evita error de escala cuando todos los valores son iguales
            vmax = vmin + 1.0

        cmap = cm.linear.YlOrRd_09.scale(vmin, vmax)
        cmap.caption = LABELS.get(variable, variable)
        cmap.add_to(m)

        def style_fn(feat):
            val = feat["properties"].get(variable)
            try:
                val_f = float(val)
                if np.isnan(val_f):
                    color = "#cccccc"
                else:
                    color = cmap(val_f)
            except (TypeError, ValueError):
                color = "#cccccc"
            return {
                "fillColor": color,
                "color": "#333333",
                "weight": 0.7,
                "fillOpacity": 0.78,
            }

        folium.GeoJson(
            gdf_p.__geo_interface__,
            style_function=style_fn,
            tooltip=GeoJsonTooltip(
                fields=["name", variable],
                aliases=["Departamento", LABELS.get(variable, variable)],
                localize=True,
                sticky=True,
            ),
        ).add_to(m)

        return m._repr_html_()

    except Exception as e:
        import traceback
        return f"<pre style='color:red;padding:15px;'>Error en mapa ({variable}, {year}):\n{e}\n\n{traceback.format_exc()}</pre>"

